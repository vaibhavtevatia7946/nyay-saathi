// Clean PDF Generator in pure Node.js
function textToPdf(text, title = 'LEGAL DRAFT - NYAY SAATHI') {
  const lines = text.split('\n');
  const margin = 54; // 0.75 in
  const pageHeight = 842; // A4 height
  const pageWidth = 595;  // A4 width
  const lineHeight = 14;
  const maxCharsPerLine = 78;

  // Word wrap lines
  const wrappedLines = [];
  for (const rawLine of lines) {
    if (rawLine.length <= maxCharsPerLine) {
      wrappedLines.push(rawLine);
    } else {
      let current = '';
      const words = rawLine.split(' ');
      for (const word of words) {
        if ((current + ' ' + word).trim().length <= maxCharsPerLine) {
          current = (current + ' ' + word).trim();
        } else {
          if (current) wrappedLines.push(current);
          current = word;
        }
      }
      if (current) wrappedLines.push(current);
    }
  }

  const linesPerPage = Math.floor((pageHeight - margin * 2 - 40) / lineHeight);
  const pages = [];
  for (let i = 0; i < wrappedLines.length; i += linesPerPage) {
    pages.push(wrappedLines.slice(i, i + linesPerPage));
  }
  if (pages.length === 0) pages.push(['']);

  const objects = [];
  const addObject = (content) => {
    objects.push(content);
    return objects.length;
  };

  const fontObj = addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  const fontBoldObj = addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');

  const pageObjIds = [];
  const contentObjIds = [];

  for (let pageIdx = 0; pageIdx < pages.length; pageIdx++) {
    const pageLines = pages[pageIdx];
    let streamContent = 'BT\n';
    
    // Header
    streamContent += `/F2 11 Tf\n1 0 0 1 ${margin} ${pageHeight - margin + 15} Tm (${title.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)')}) Tj\n`;
    streamContent += `0.5 w\nET\nq 0.75 0.75 0.75 RG ${margin} ${pageHeight - margin + 8} m ${pageWidth - margin} ${pageHeight - margin + 8} l S Q\nBT\n`;
    
    // Body Text
    streamContent += `/F1 9.5 Tf\n`;
    let y = pageHeight - margin - 15;
    for (const line of pageLines) {
      const safeLine = line.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
      streamContent += `1 0 0 1 ${margin} ${y} Tm (${safeLine}) Tj\n`;
      y -= lineHeight;
    }

    // Footer with Page Number
    const pageNumText = `Page ${pageIdx + 1} of ${pages.length}  |  Generated by AI Nyay Saathi`;
    streamContent += `/F1 8 Tf\n1 0 0 1 ${margin} ${margin - 25} Tm (${pageNumText}) Tj\n`;
    streamContent += 'ET\n';

    const contentObj = addObject(`<< /Length ${Buffer.byteLength(streamContent)} >>\nstream\n${streamContent}\nendstream`);
    contentObjIds.push(contentObj);
  }

  const pagesObjIndex = objects.length + 1;
  for (let i = 0; i < pages.length; i++) {
    const pageObj = addObject(`<< /Type /Page /Parent ${pagesObjIndex} 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Contents ${contentObjIds[i]} 0 R /Resources << /Font << /F1 ${fontObj} 0 R /F2 ${fontBoldObj} 0 R >> >> >>`);
    pageObjIds.push(pageObj);
  }

  const pagesObj = addObject(`<< /Type /Pages /Kids [${pageObjIds.map(id => id + ' 0 R').join(' ')}] /Count ${pageObjIds.length} >>`);
  const catalogObj = addObject(`<< /Type /Catalog /Pages ${pagesObj} 0 R >>`);

  let pdf = '%PDF-1.4\n';
  const xref = [0];
  let offset = pdf.length;

  for (let i = 0; i < objects.length; i++) {
    xref.push(offset);
    const objStr = `${i + 1} 0 obj\n${objects[i]}\nendobj\n`;
    pdf += objStr;
    offset += Buffer.byteLength(objStr);
  }

  const xrefOffset = offset;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) {
    pdf += String(xref[i]).padStart(10, '0') + ' 00000 n \n';
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogObj} 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return Buffer.from(pdf);
}

